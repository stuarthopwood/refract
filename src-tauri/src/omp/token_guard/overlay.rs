// Generated `token-guard-overlay.yml`; only a Session launched before the migration to the global config reads it.

use std::collections::BTreeMap;
use std::future::Future;
use std::io;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};

use serde_json::Value;

use super::values::{ValueMap, STORE_VERSION};

pub const FILE_NAME: &str = "token-guard-overlay.yml";

/// First line of every Refract-generated overlay; how `refresh_legacy` tells one from a user's file.
const HEADER_PREFIX: &str = "# refract-overlay-version:";

#[derive(Default)]
struct Node {
    leaf: Option<Value>,
    children: BTreeMap<String, Node>,
}

fn build_tree(values: &ValueMap) -> Node {
    let mut root = Node::default();
    for (key, value) in values {
        let mut node = &mut root;
        for part in key.split('.') {
            node = node.children.entry(part.to_string()).or_default();
        }
        node.leaf = Some(value.clone());
    }
    root
}

// A JSON scalar is also a valid YAML scalar (double-quoted strings, bare numbers and booleans).
fn scalar(value: &Value) -> String {
    value.to_string()
}

fn emit_value(out: &mut String, indent: usize, key: &str, value: &Value) {
    let pad = " ".repeat(indent);
    match value {
        Value::Object(map) if !map.is_empty() => {
            out.push_str(&format!("{pad}{key}:\n"));
            for (k, v) in map {
                out.push_str(&format!(
                    "{pad}  {}: {}\n",
                    scalar(&Value::String(k.clone())),
                    scalar(v)
                ));
            }
        }
        Value::Object(_) => out.push_str(&format!("{pad}{key}: {{}}\n")),
        Value::Array(items) if !items.is_empty() => {
            out.push_str(&format!("{pad}{key}:\n"));
            for item in items {
                out.push_str(&format!("{pad}  - {}\n", scalar(item)));
            }
        }
        Value::Array(_) => out.push_str(&format!("{pad}{key}: []\n")),
        other => out.push_str(&format!("{pad}{key}: {}\n", scalar(other))),
    }
}

fn emit_node(out: &mut String, indent: usize, node: &Node) {
    for (key, child) in &node.children {
        match &child.leaf {
            Some(value) => emit_value(out, indent, key, value),
            None => {
                out.push_str(&format!("{}{key}:\n", " ".repeat(indent)));
                emit_node(out, indent + 2, child);
            }
        }
    }
}

/// Renders the overlay file text for `values`. With prewalk off the judge is silenced too, since
/// `prewalk.auto` adds a model call per task independent of `prewalk.enabled` (#695). A positive
/// `compaction.thresholdTokens` would beat the percent, so the overlay always sends -1.
pub fn render(values: &ValueMap) -> String {
    let mut values = values.clone();
    values.insert("compaction.thresholdTokens".to_string(), Value::from(-1));
    if values.get("prewalk.enabled") == Some(&Value::Bool(false)) {
        values.insert("prewalk.auto".to_string(), Value::String("off".to_string()));
    }
    let mut out = format!(
        "{HEADER_PREFIX} {STORE_VERSION}\n# Generated by Refract; edit the values in Settings > OMP instead.\n"
    );
    emit_node(&mut out, 0, &build_tree(&values));
    out
}

pub fn path(dir: &Path) -> PathBuf {
    dir.join(FILE_NAME)
}

/// Pre-#1767 behaviour, used only while the migration to the global config has not succeeded.
pub async fn write_legacy(dir: &Path, values: &ValueMap) -> io::Result<PathBuf> {
    let file = path(dir);
    super::write_atomic_if_changed(&file, render(values).as_bytes()).await?;
    Ok(file)
}

/// Legacy variant of `write_legacy` with a per-Session plan state.
pub async fn write_legacy_plan_variant(
    dir: &Path,
    values: &ValueMap,
    plan: bool,
) -> io::Result<PathBuf> {
    let file = plan_variant_path(dir, plan);
    super::write_atomic_if_changed(&file, render(values).as_bytes()).await?;
    Ok(file)
}

fn plan_variant_path(dir: &Path, plan: bool) -> PathBuf {
    dir.join(if plan {
        "token-guard-overlay-plan-on.yml"
    } else {
        "token-guard-overlay-plan-off.yml"
    })
}

fn is_generated_overlay(text: &str) -> bool {
    text.starts_with(HEADER_PREFIX)
}

async fn is_generated_file(file: &Path) -> bool {
    tokio::fs::read_to_string(file)
        .await
        .is_ok_and(|text| is_generated_overlay(&text))
}

/// Set once a Session launches on the legacy overlay. Omp processes die with Refract (job object),
/// so only a launch in this process can leave a Session reading a stale overlay.
static LEGACY_SESSION_LAUNCHED: AtomicBool = AtomicBool::new(false);

pub fn note_legacy_launch() {
    LEGACY_SESSION_LAUNCHED.store(true, Ordering::Release);
}

pub fn legacy_session_launched() -> bool {
    LEGACY_SESSION_LAUNCHED.load(Ordering::Acquire)
}

/// A Session launched while the migration was pending keeps reading its legacy overlay between
/// turns, and that overlay beats the global config. Rewrites every Refract-generated legacy overlay
/// still on disk so a Settings write reaches those Sessions too; a file Refract did not generate is
/// never touched. The one-key plan variants are left alone: they set `plan.defaultOnStartup`, which
/// only applies at startup.
pub async fn refresh_legacy(dir: &Path, values: &ValueMap) -> io::Result<()> {
    refresh_legacy_with(dir, values, |file, text| async move {
        super::write_atomic_if_changed(&file, text.as_bytes()).await
    })
    .await
}

async fn refresh_legacy_with<W, F>(dir: &Path, values: &ValueMap, write: W) -> io::Result<()>
where
    W: Fn(PathBuf, String) -> F,
    F: Future<Output = io::Result<()>>,
{
    let base = path(dir);
    if is_generated_file(&base).await {
        write(base, render(values)).await?;
    }
    for plan in [true, false] {
        let file = plan_variant_path(dir, plan);
        if is_generated_file(&file).await {
            let mut with_plan = values.clone();
            with_plan.insert("plan.defaultOnStartup".to_string(), plan.into());
            write(file, render(&with_plan)).await?;
        }
    }
    Ok(())
}

/// A per-Session working mode overrides the global `plan.defaultOnStartup` through this one-key overlay.
pub async fn write_plan_variant(dir: &Path, plan: bool) -> io::Result<PathBuf> {
    let file = plan_variant_path(dir, plan);
    let text = format!("plan:\n  defaultOnStartup: {plan}\n");
    super::write_atomic_if_changed(&file, text.as_bytes()).await?;
    Ok(file)
}

#[cfg(test)]
mod tests {
    use super::super::values::defaults;
    use super::*;

    #[test]
    fn renders_nested_yaml_with_version_header() {
        let text = render(&defaults());
        assert!(text.starts_with("# refract-overlay-version: 2\n"));
        assert!(text.contains("task:\n  maxConcurrency: 6\n  softRequestBudget: 60\n"));
        assert!(text.contains("providers:\n  cacheWarming: \"idle\"\n"));
        assert!(text.contains("  thresholdPercent: 70\n"));
        assert!(text.contains("  thresholdTokens: -1\n"));
        assert!(text.contains("  modelThresholds: {}\n"));
        assert!(text.contains("  methodOrder:\n    - \"snapcompact\"\n    - \"shake\"\n"));
        assert!(text.contains("  systemPrompt: \"none\"\n"));
        assert!(text.contains("modelRoles:\n  advisor: \"github-copilot/gemini-4-argon:auto\"\n"));
    }

    #[test]
    fn default_overlay_omits_cache_retention_and_overrides() {
        let text = render(&defaults());
        for absent in [
            "cacheRetention",
            "modelOverrides",
            "promptCache",
            "agentSoftRequestBudget",
        ] {
            assert!(!text.contains(absent), "{absent}");
        }
    }

    fn scratch(name: &str) -> PathBuf {
        let dir =
            std::env::temp_dir().join(format!("refract-overlay-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn with_budget(budget: i64) -> ValueMap {
        let mut values = defaults();
        values.insert("task.softRequestBudget".to_string(), Value::from(budget));
        values
    }

    #[tokio::test]
    async fn rewrites_the_legacy_overlay_and_full_plan_variants() {
        let dir = scratch("rewrites");
        write_legacy(&dir, &with_budget(60)).await.unwrap();
        write_legacy_plan_variant(&dir, &with_budget(60), true)
            .await
            .unwrap();
        refresh_legacy(&dir, &with_budget(25)).await.unwrap();
        let base = std::fs::read_to_string(path(&dir)).unwrap();
        assert!(base.contains("softRequestBudget: 25\n"));
        let on = std::fs::read_to_string(plan_variant_path(&dir, true)).unwrap();
        assert!(on.contains("softRequestBudget: 25\n"));
        assert!(on.contains("defaultOnStartup: true\n"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[tokio::test]
    async fn leaves_one_key_plan_variants_and_absent_files_alone() {
        let dir = scratch("untouched");
        write_plan_variant(&dir, false).await.unwrap();
        refresh_legacy(&dir, &with_budget(25)).await.unwrap();
        assert!(!path(&dir).exists());
        assert!(!plan_variant_path(&dir, true).exists());
        let off = std::fs::read_to_string(plan_variant_path(&dir, false)).unwrap();
        assert_eq!(off, "plan:\n  defaultOnStartup: false\n");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[tokio::test]
    async fn leaves_an_overlay_refract_did_not_generate_alone() {
        let dir = scratch("foreign");
        let foreign = "task:\n  softRequestBudget: 7\n";
        std::fs::write(path(&dir), foreign).unwrap();
        std::fs::write(plan_variant_path(&dir, true), foreign).unwrap();
        refresh_legacy(&dir, &with_budget(25)).await.unwrap();
        assert_eq!(std::fs::read_to_string(path(&dir)).unwrap(), foreign);
        let on = std::fs::read_to_string(plan_variant_path(&dir, true)).unwrap();
        assert_eq!(on, foreign);
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[tokio::test]
    async fn an_unwritable_plan_variant_is_an_error_after_the_base_overlay_is_rewritten() {
        let dir = scratch("unwritable");
        write_legacy(&dir, &with_budget(60)).await.unwrap();
        write_legacy_plan_variant(&dir, &with_budget(60), true)
            .await
            .unwrap();
        let blocked = plan_variant_path(&dir, true);
        let result = refresh_legacy_with(&dir, &with_budget(25), |file, text| {
            let blocked = blocked.clone();
            async move {
                if file == blocked {
                    return Err(io::Error::new(io::ErrorKind::PermissionDenied, "read-only"));
                }
                super::super::write_atomic_if_changed(&file, text.as_bytes()).await
            }
        })
        .await;
        assert_eq!(result.unwrap_err().kind(), io::ErrorKind::PermissionDenied);
        let base = std::fs::read_to_string(path(&dir)).unwrap();
        assert!(base.contains("softRequestBudget: 25\n"));
        let on = std::fs::read_to_string(blocked).unwrap();
        assert!(on.contains("softRequestBudget: 60\n"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn only_the_shared_header_marks_a_generated_overlay() {
        assert!(is_generated_overlay(&render(&defaults())));
        assert!(!is_generated_overlay("plan:\n  defaultOnStartup: true\n"));
    }
}
